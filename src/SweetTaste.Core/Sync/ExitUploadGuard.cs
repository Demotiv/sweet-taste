namespace SweetTaste.Core.Sync;

/// <summary>
/// Решает, можно ли без вопросов выгрузить базу в облако при закрытии приложения.
/// </summary>
/// <remarks>
/// Ручная выгрузка показывает подтверждение с тем, что сейчас в облаке. Выгрузка при
/// закрытии никого не спрашивает, поэтому она обязана отказаться всякий раз, когда
/// замена облака может стереть чужие данные:
/// <list type="bullet">
/// <item>локальная база пуста — например, свежая установка, где ещё не скачали облако;</item>
/// <item>компьютер ни разу не обменивался данными с этим облаком;</item>
/// <item>облако обновлялось после последнего обмена — данные выгрузил другой компьютер.</item>
/// </list>
/// Пустое облако заменять можно: терять в нём нечего.
/// </remarks>
public static class ExitUploadGuard
{
    /// <summary>
    /// Допуск при сравнении меток: облако хранит время с точностью до микросекунды,
    /// а локальная метка — до десятой доли микросекунды.
    /// </summary>
    private static readonly TimeSpan Tolerance = TimeSpan.FromMilliseconds(1);

    /// <summary>null — выгружать можно; иначе причина отказа для журнала и настроек.</summary>
    public static string? Check(int localRows, CloudState? cloud, DateTimeOffset? cloudSnapshotSeenAt)
    {
        if (localRows == 0)
        {
            return "база на этом компьютере пуста, а пустая выгрузка стёрла бы облако";
        }

        if (cloud is null)
        {
            return null;
        }

        if (cloudSnapshotSeenAt is null)
        {
            return "этот компьютер ещё не обменивался данными с облаком. " +
                   "Один раз выгрузите или загрузите данные вручную в настройках";
        }

        if ((cloud.TakenAt - cloudSnapshotSeenAt.Value).Duration() > Tolerance)
        {
            return "облако обновили с другого компьютера после последнего обмена. " +
                   "Загрузите данные из облака или выгрузите их вручную в настройках";
        }

        return null;
    }
}
